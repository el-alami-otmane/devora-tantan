const canvas = document.querySelector('#networkCanvas');
const context = canvas.getContext('2d');
const hero = document.querySelector('.hero');
const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
let particles = [];
let canvasWidth = 0;
let canvasHeight = 0;
let animationFrame = 0;

function resizeCanvas() {
  const ratio = Math.min(window.devicePixelRatio || 1, 2);
  canvasWidth = hero.clientWidth;
  canvasHeight = hero.clientHeight;
  canvas.width = canvasWidth * ratio;
  canvas.height = canvasHeight * ratio;
  canvas.style.width = `${canvasWidth}px`;
  canvas.style.height = `${canvasHeight}px`;
  context.setTransform(ratio, 0, 0, ratio, 0, 0);
  const count = Math.max(22, Math.min(48, Math.round(canvasWidth / 32)));
  particles = Array.from({ length: count }, () => ({
    x: Math.random() * canvasWidth,
    y: Math.random() * canvasHeight,
    vx: (Math.random() - .5) * .18,
    vy: (Math.random() - .5) * .18,
    r: Math.random() * 1.2 + .45
  }));
}

function drawNetwork() {
  context.clearRect(0, 0, canvasWidth, canvasHeight);
  const light = root.dataset.theme === 'light';
  context.fillStyle = light ? 'rgba(8,120,238,.36)' : 'rgba(83,214,255,.42)';
  particles.forEach((particle, index) => {
    if (!prefersReducedMotion) {
      particle.x += particle.vx;
      particle.y += particle.vy;
      if (particle.x < 0 || particle.x > canvasWidth) particle.vx *= -1;
      if (particle.y < 0 || particle.y > canvasHeight) particle.vy *= -1;
    }
    context.beginPath();
    context.arc(particle.x, particle.y, particle.r, 0, Math.PI * 2);
    context.fill();
    for (let otherIndex = index + 1; otherIndex < particles.length; otherIndex += 1) {
      const other = particles[otherIndex];
      const dx = particle.x - other.x;
      const dy = particle.y - other.y;
      const distance = Math.hypot(dx, dy);
      if (distance < 125) {
        context.strokeStyle = light ? `rgba(8,120,238,${(1 - distance / 125) * .1})` : `rgba(83,214,255,${(1 - distance / 125) * .11})`;
        context.lineWidth = .7;
        context.beginPath();
        context.moveTo(particle.x, particle.y);
        context.lineTo(other.x, other.y);
        context.stroke();
      }
    }
  });
  if (!prefersReducedMotion) animationFrame = requestAnimationFrame(drawNetwork);
}

